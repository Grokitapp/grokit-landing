// One-time (re-runnable) image optimiser.
//   npm i -D sharp
//   node scripts/optimize-images.mjs
// Run from the project root. Originals are never modified or deleted.
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';

await mkdir('public', { recursive: true });

const clear = { r: 0, g: 0, b: 0, alpha: 0 };

const jobs = [
  // Hero: in public/ so index.html can preload it by a fixed URL
  { src: 'assets/grokit-hero-mascot.png', out: 'public/hero-mascot.webp', w: 1000, webp: true, key: 'hero' },
  // Small icon for lesson nodes (previously loaded the full hero image)
  { src: 'assets/grokit-hero-mascot.png', out: 'assets/grokit-node.webp', w: 96, webp: true },
  { src: 'assets/grokit-grounded.png', out: 'assets/grokit-grounded.webp', w: 920, webp: true, key: 'grounded' },
  { src: 'assets/grokit-octo.png', out: 'assets/grokit-octo.webp', w: 320, webp: true },
  // Favicons: square. Use a square source (the mascot face works well).
  { src: 'assets/grokit-octo.png', out: 'public/favicon-32.png', w: 32, h: 32 },
  { src: 'assets/grokit-octo.png', out: 'public/favicon-192.png', w: 192, h: 192 },
  { src: 'assets/grokit-octo.png', out: 'public/apple-touch-icon.png', w: 180, h: 180 },
];

const sizes = {};

for (const job of jobs) {
  let img = sharp(job.src).resize(job.w, job.h, {
    fit: job.h ? 'contain' : 'inside',
    background: clear,
    withoutEnlargement: !job.h,
  });
  img = job.webp ? img.webp({ quality: 82 }) : img.png({ compressionLevel: 9 });

  const info = await img.toFile(job.out);
  console.log(`${job.out}: ${info.width}x${info.height}, ${(info.size / 1024).toFixed(0)} KB`);

  if (job.key) sizes[job.key] = { width: info.width, height: info.height };
}

await writeFile(
  'lib/imageMeta.ts',
  `// Intrinsic sizes of the optimised images, used for width/height attributes so
// the layout doesn't jump while they load.
// Regenerated by \`node scripts/optimize-images.mjs\`, so don't edit by hand.
export const IMAGE_SIZES = ${JSON.stringify(sizes, null, 2)} as const;
`,
);
console.log('lib/imageMeta.ts updated');
