/**
 * Everything the journey page needs, in one request. The page caches this, so a
 * journey that was opened before appears instantly and refreshes in the
 * background.
 */
export async function loadJourneyRaw(courseId: string) {
  requireId(courseId, 'COURSE_ID_REQUIRED');

  const [course, phases, lessons, progress] = await Promise.all([
    getCourse(courseId),
    listPhasesForCourse(courseId),
    listLessonsForCourse(courseId),
    listProgressForCourse(courseId),
  ]);

  if (!course) throw new Error('JOURNEY_NOT_FOUND');

  return { course, phases, lessons, progress };
}

export type JourneyRaw = Awaited<ReturnType<typeof loadJourneyRaw>>;

/**
 * Refresh this journey's cached copy right away (if it has one), so its path
 * shows the new progress the moment the learner returns to it.
 */
function refreshJourneyCache(courseId: string): void {
  void refreshIfCached(cacheKeys.journey(courseId), () =>
    loadJourneyRaw(courseId),
  );
}

/** What the server decided when a lesson was completed. */
export interface LessonCompletionResult {
  xp: number;
  correct: number;
  total: number;
  /** True when the lesson had been completed before; no XP is added again. */
  alreadyCompleted: boolean;
}

/**
 * Finish a lesson.
 *
 * `answers` holds the option the learner picked first for each practice
 * question, in order (an empty list when there was no practice). The server
 * grades them, decides the XP and saves the progress, so the browser can no
 * longer award XP itself. After that, the next zone is unlocked if this was
 * the last lesson of the current one.
 */
export async function markLessonComplete(
  courseId: string,
  lessonId: string,
  answers: number[] = [],
): Promise<LessonCompletionResult> {
  requireId(courseId, 'COURSE_ID_REQUIRED');
  requireId(lessonId, 'LESSON_ID_REQUIRED');

  const lesson = await getLesson(lessonId);

  if (!lesson) {
    throw new Error('LESSON_NOT_FOUND');
  }

  if (lesson.courseId !== courseId) {
    throw new Error('LESSON_COURSE_MISMATCH');
  }

  const { data, errors } = await client.mutations.completeLesson(
    { lessonId, answers: JSON.stringify(answers) },
    USER_POOL,
  );

  throwIfErrors(errors, 'LESSON_COMPLETION_FAILED');

  if (!data) {
    throw new Error('LESSON_COMPLETION_FAILED');
  }

  // Completion is saved before progression. If unlocking fails, finishing
  // the lesson again reuses the saved completion and retries the unlock.
  await advancePhaseIfComplete(courseId, lessonId);
  refreshJourneyCache(courseId);

  return {
    xp: data.xp,
    correct: data.correct,
    total: data.total,
    alreadyCompleted: data.alreadyCompleted,
  };
}

// ─── Phase progression ──────────────────────────────────────────────────────

async function advancePhaseIfComplete(
  courseId: string,
  lessonId: string,
): Promise<void> {
  const lesson = await getLesson(lessonId);

  if (!lesson) {
    throw new Error('COMPLETED_LESSON_NOT_FOUND');
  }

  if (lesson.courseId !== courseId) {
    throw new Error('LESSON_COURSE_MISMATCH');
  }

  const phase = await getPhase(lesson.phaseId);

  if (!phase) {
    throw new Error('LESSON_PHASE_NOT_FOUND');
  }

  if (phase.courseId !== courseId) {
    throw new Error('LESSON_PHASE_COURSE_MISMATCH');
  }

  const [phaseLessons, progress, phases] = await Promise.all([
    listLessonsForPhase(phase.id),
    listProgressForCourse(courseId),
    listPhasesForCourse(courseId),
  ]);

  if (
    phaseLessons.length === 0 ||
    phaseLessons.some((item) => item.courseId !== courseId)
  ) {
    return;
  }

  // The list can lag a moment behind a lesson that was just completed.
  const completedLessonIds = new Set(
    progress.map((item) => item.lessonId),
  );
  completedLessonIds.add(lessonId);

  const phaseComplete = phaseLessons.every((item) =>
    completedLessonIds.has(item.id),
  );

  if (!phaseComplete) return;

  // Find the nearest subsequent phase without assuming consecutive orders.
  const nextPhase = phases
    .filter((candidate) => candidate.order > phase.order)
    .sort((a, b) => a.order - b.order)[0];

  if (!nextPhase) return;

  await unlockPhase(nextPhase.id);
}

export async function unlockPhase(phaseId: string) {
  requireId(phaseId, 'PHASE_ID_REQUIRED');

  const phase = await getPhase(phaseId);

  if (!phase) {
    throw new Error('PHASE_NOT_FOUND');
  }

  if (phase.locked === false) {
    return phase;
  }

  const { data, errors } = await client.models.Phase.update({
    id: phaseId,
    locked: false,
  });

  throwIfErrors(errors, 'PHASE_UNLOCK_FAILED');

  if (!data) {
    throw new Error('PHASE_UNLOCK_FAILED');
  }

  return data;
}