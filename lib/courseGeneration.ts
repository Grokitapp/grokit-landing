const USER_POOL = { authMode: 'userPool' } as const;

type GraphqlError = {
  message?: string;
};

type ExperienceLevel =
  | 'new'
  | 'beginner'
  | 'intermediate'
  | 'advanced';

type PersonalizationProfile = {
  experienceLevel: ExperienceLevel;
  existingKnowledge: string[];
  learningFocus: string;
  focusAreas: string[];
};

const EXPERIENCE_LEVELS = new Set<ExperienceLevel>([
  'new',
  'beginner',
  'intermediate',
  'advanced',
]);

function throwIfErrors(
  errors?: readonly GraphqlError[] | null,
  code = 'REQUEST_FAILED',
): void {
  if (!errors?.length) return;

  console.error(`[courseGeneration] ${code}:`, errors);
  throw new Error(code);
}

function requireId(id: string, code: string): void {
  if (typeof id !== 'string' || !id.trim()) {
    throw new Error(code);
  }
}

function normalizeStringList(value: unknown): string[] {
  if (!Array.isArray(value)) return [];

  return [
    ...new Set(
      value
        .filter((item): item is string => typeof item === 'string')
        .map((item) => item.trim())
        .filter(Boolean),
    ),
  ];
}

function normalizePersonalization(
  profile?: PersonalizationProfile,
): PersonalizationProfile | undefined {
  if (profile == null) return undefined;

  if (
    typeof profile !== 'object' ||
    !EXPERIENCE_LEVELS.has(profile.experienceLevel)
  ) {
    throw new Error('PERSONALIZATION_PROFILE_INVALID');
  }

  return {
    experienceLevel: profile.experienceLevel,
    existingKnowledge: normalizeStringList(profile.existingKnowledge),
    learningFocus:
      typeof profile.learningFocus === 'string'
        ? profile.learningFocus.trim()
        : '',
    focusAreas: normalizeStringList(profile.focusAreas),
  };
}

// ─── Polling helper ─────────────────────────────────────────────────────────
//
// Course outlines and lessons are generated by background workers, so the
// mutations return immediately with status GENERATING. These helpers wait for
// the worker to finish, so callers (Generating.tsx, PhaseDetail.tsx,
// LessonPlayer.tsx) keep working exactly as before: they await one promise
// and receive the finished record.

const sleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

async function pollUntil<T>(
  read: () => Promise<T | null | undefined>,
  isDone: (value: T) => boolean,
  options: { intervalMs: number; timeoutMs: number; timeoutCode: string },
): Promise<T> {
  const deadline = Date.now() + options.timeoutMs;
  let consecutiveReadFailures = 0;

  while (Date.now() < deadline) {
    await sleep(options.intervalMs);

    try {
      const value = await read();
      consecutiveReadFailures = 0;

      if (value && isDone(value)) return value;
    } catch (error) {
      // Tolerate brief network blips; give up if reads keep failing.
      consecutiveReadFailures += 1;
      console.warn('[courseGeneration] Status check failed:', error);

      if (consecutiveReadFailures >= 4) throw error;
    }
  }

  throw new Error(options.timeoutCode);
}

// ─── Course generation ──────────────────────────────────────────────────────

type OnboardingSnapshot = Partial<{
  motivations: string[];
  interests: string[];
  startingPreference: string;
  comprehensionPreferences: string[];
  desiredOutcomes: string[];
  timeCommitment: string;
}>;

/**
 * Snapshot of the learner's onboarding answers. It is saved on the course so
 * the lesson worker can personalise every lesson later without any extra
 * profile lookups. A failure here must never block course creation.
 */
async function loadOnboardingSnapshot(): Promise<OnboardingSnapshot | undefined> {
  try {
    const profile = await getProfile();
    if (!profile) return undefined;

    const snapshot: OnboardingSnapshot = {};

    const motivations = normalizeStringList(profile.motivations);
    const interests = normalizeStringList(profile.interests);
    const comprehension = normalizeStringList(profile.comprehensionPreferences);
    const outcomes = normalizeStringList(profile.desiredOutcomes);

    if (motivations.length) snapshot.motivations = motivations;
    if (interests.length) snapshot.interests = interests;
    if (comprehension.length) snapshot.comprehensionPreferences = comprehension;
    if (outcomes.length) snapshot.desiredOutcomes = outcomes;

    if (typeof profile.startingPreference === 'string' && profile.startingPreference.trim()) {
      snapshot.startingPreference = profile.startingPreference.trim();
    }

    if (typeof profile.timeCommitment === 'string' && profile.timeCommitment.trim()) {
      snapshot.timeCommitment = profile.timeCommitment.trim();
    }

    return Object.keys(snapshot).length ? snapshot : undefined;
  } catch (error) {
    console.warn('[courseGeneration] Could not load onboarding profile:', error);
    return undefined;
  }
}

const COURSE_POLL_INTERVAL_MS = 2500;
const COURSE_TIMEOUT_MS = 6 * 60_000;

export async function createCourseFromPrompt(
  topic: string,
  personalizationProfile?: PersonalizationProfile,
) {
  const normalizedTopic =
    typeof topic === 'string' ? topic.trim() : '';

  if (!normalizedTopic) {
    throw new Error('COURSE_TOPIC_REQUIRED');
  }

  const courseTime = normalizePersonalization(personalizationProfile);
  const onboarding = await loadOnboardingSnapshot();

  // Course-time answers and onboarding answers travel together.
  const payload = {
    ...(courseTime ?? {}),
    ...(onboarding ? { onboarding } : {}),
  };

  try {
    // Returns right away with a GENERATING course; the worker does the rest.
    const { data, errors } = await client.mutations.generateOutline(
      {
        topic: normalizedTopic,
        ...(Object.keys(payload).length
          ? { personalizationProfile: JSON.stringify(payload) }
          : {}),
      },
      USER_POOL,
    );

    const limitError = limitErrorFrom(errors);

    if (limitError) throw limitError;

    throwIfErrors(errors, 'COURSE_GENERATION_FAILED');

    if (!data) {
      throw new Error('COURSE_GENERATION_EMPTY');
    }

    const finished =
      data.status === 'READY' || data.status === 'FAILED'
        ? data
        : await pollUntil(
            () => getCourse(data.id),
            (course) => course.status === 'READY' || course.status === 'FAILED',
            {
              intervalMs: COURSE_POLL_INTERVAL_MS,
              timeoutMs: COURSE_TIMEOUT_MS,
              timeoutCode: 'COURSE_GENERATION_TIMEOUT',
            },
          );

    if (finished.status === 'FAILED') {
      console.error('[courseGeneration] Worker reported failure:', finished.generationError);
      throw new Error('COURSE_GENERATION_FAILED');
    }

    // A new journey exists now; the Library list must pick it up.
    invalidate(cacheKeys.myJourneys);

    return finished;
  } catch (error) {
    // An expected outcome, not a failure: pass it on for the screen to explain.
    if (error instanceof LimitReachedError) throw error;

    console.error('[courseGeneration] Course generation failed:', error);

    if (
      error instanceof Error &&
      (error.message.startsWith('COURSE_') ||
        error.message === 'PERSONALIZATION_PROFILE_INVALID')
    ) {
      throw error;
    }

    throw new Error('COURSE_GENERATION_FAILED');
  }
}

const LESSON_POLL_INTERVAL_MS = 2500;
const LESSON_TIMEOUT_MS = 5 * 60_000;

export async function generateLessonContent(lessonId: string) {
  requireId(lessonId, 'LESSON_ID_REQUIRED');

  try {
    // Returns right away (status GENERATING, or READY if it already existed).
    const { data, errors } = await client.mutations.generateLesson(
      { lessonId },
      USER_POOL,
    );

    const limitError = limitErrorFrom(errors);

    if (limitError) throw limitError;

    throwIfErrors(errors, 'LESSON_GENERATION_FAILED');

    if (!data) {
      throw new Error('LESSON_GENERATION_EMPTY');
    }

    const finished =
      data.status === 'READY' || data.status === 'FAILED'
        ? data
        : await pollUntil(
            () => getLesson(lessonId),
            (lesson) => lesson.status === 'READY' || lesson.status === 'FAILED',
            {
              intervalMs: LESSON_POLL_INTERVAL_MS,
              timeoutMs: LESSON_TIMEOUT_MS,
              timeoutCode: 'LESSON_GENERATION_TIMEOUT',
            },
          );

    if (finished.status === 'FAILED') {
      console.error('[courseGeneration] Worker reported failure:', finished.generationError);
      throw new Error('LESSON_GENERATION_FAILED');
    }

    return finished;
  } catch (error) {
    if (error instanceof LimitReachedError) throw error;

    console.error('[courseGeneration] Lesson generation failed:', error);

    if (
      error instanceof Error &&
      error.message.startsWith('LESSON_')
    ) {
      throw error;
    }

    throw new Error('LESSON_GENERATION_FAILED');
  }
}

/** What the lesson popup shows once a lesson is ready. */
export interface LessonPreview {
  /** "cards" for the card lessons, "article" for older lessons. */
  format: 'cards' | 'article';
  cards: number;
  /** 0 while the practice questions are still being written. */
  questions: number;
  minutes: number;
}

function parseStoredJson(value: unknown): unknown {
  let current = value;

  for (let i = 0; i < 2 && typeof current === 'string'; i += 1) {
    try {
      current = JSON.parse(current);
    } catch {
      return null;
    }
  }

  return current;
}

/** Counts cards, questions and minutes for a lesson record (either format). */
export function getLessonPreview(lesson: {
  content?: unknown;
  practice?: unknown;
  practiceStatus?: string | null;
  coreContent?: string | null;
  quiz?: unknown;
}): LessonPreview | null {
  const content = readLessonContent(lesson.content);

  if (content) {
    const practice =
      lesson.practiceStatus === 'READY' ? readPractice(lesson.practice) : null;

    return {
      format: 'cards',
      cards: content.cards.length,
      questions: practice?.length ?? 0,
      minutes: Math.max(1, Math.round(content.estimatedMinutes || 0) || 4),
    };
  }

  if (typeof lesson.coreContent === 'string' && lesson.coreContent.trim()) {
    const words = lesson.coreContent.trim().split(/\s+/).length;
    const quiz = parseStoredJson(lesson.quiz);
    const questions = Array.isArray(quiz) ? quiz.length : 0;

    return {
      format: 'article',
      cards: 0,
      questions,
      minutes: Math.max(2, Math.round(words / 180 + questions * 0.4)),
    };
  }

  return null;
}

// ─── Course reads ───────────────────────────────────────────────────────────

export async function listCourses() {
  const { data, errors } = await client.models.Course.list();

  throwIfErrors(errors, 'COURSES_LOAD_FAILED');

  return [...(data ?? [])].sort((a, b) => {
    const aDate = a.updatedAt ?? a.createdAt ?? '';
    const bDate = b.updatedAt ?? b.createdAt ?? '';

    return bDate.localeCompare(aDate);
  });
}

export async function getCourse(courseId: string) {
  requireId(courseId, 'COURSE_ID_REQUIRED');

  const { data, errors } = await client.models.Course.get({
    id: courseId,
  });

  throwIfErrors(errors, 'COURSE_LOAD_FAILED');

  return data;
}

